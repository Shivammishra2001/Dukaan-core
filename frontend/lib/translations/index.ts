type TFn = (key: string) => string;

/** Intl locale for dates/times in the active UI language — Devanagari month names for `hi`, Indian English otherwise; digits stay Latin in both (REQUIREMENTS.md §9). */
export function dateLocale(language: Language): string {
  return language === 'hi' ? 'hi-IN' : 'en-IN';
}

/**
 * Translates an enum-like backend value (`CASH`, `BOOKED`, `OPENING_BALANCE`,
 * ...) via `${namespace}.${value}`, falling back to the raw value when the
 * dictionary has no entry — so an unexpected new enum value renders as-is
 * instead of as a dotted key.
 */
export function translateEnum(t: TFn, namespace: string, value: string): string {
  const key = `${namespace}.${value}`;
  const out = t(key);
  return out === key ? value : out;
}

/**
 * Renders an error for display. API/client errors travel as codes
 * (`ERR_NETWORK`, `HTTP_502`, ...) and are mapped through `error.*`; unknown
 * codes get a generic message with the code kept in brackets for support.
 * Anything that is not a code (an already-translated message) passes
 * through unchanged, so this is safe to wrap around every rendered error.
 */
export function translateError(t: TFn, error: string): string {
  const out = translateEnum(t, 'error', error);
  if (out !== error) return out;
  if (/^HTTP_\d{3}$/.test(error)) return `${t('error.ERR_UPSTREAM')} (${error})`;
  if (/^ERR_[A-Z_]+$/.test(error)) return `${t('error.ERR_UNKNOWN')} (${error})`;
  return error;
}
